// Runs MVP_SPEC section 15 (the demo scenario) against the API layer, plus server-side permission denials.
// Usage: node tests/acceptance.mjs
import { webcrypto } from 'node:crypto'

const store = new Map()
globalThis.localStorage = { getItem: (k) => (store.has(k) ? store.get(k) : null), setItem: (k, v) => store.set(k, String(v)), removeItem: (k) => store.delete(k) }
if (!globalThis.crypto?.randomUUID) globalThis.crypto = webcrypto

const { dispatch, resetDemo } = await import('../src/mock/server.js')
resetDemo()

let passed = 0
let failed = 0
const call = (path, payload) => dispatch(path, payload).data
const as = (email) => call('auth/login', { email, password: 'demo' })
function ok(name, cond) { if (cond) { passed++ } else { failed++; console.log('  FAIL:', name) } }
function step(name) { console.log(`\n${name}`) }
function denied(name, fn, code) {
  try { fn(); failed++; console.log('  FAIL (was allowed):', name) } catch (e) {
    if (code && e.code !== code) { failed++; console.log(`  FAIL (code ${e.code}, wanted ${code}):`, name, '-', e.message) } else { passed++ }
  }
}
const aid = () => `a_${crypto.randomUUID()}`
// Outline items (MVP_SPEC section 5). Role ids: 1 HR Officer, 2 IT Support, 3 Line Manager, 4 Payroll. System ids: 1 HRIS, 2 Service Desk.
const act = (label, role_id, extra = {}) => ({ id: aid(), kind: 'activity', label, role_id, system_id: null, tasks: [{ id: `t_${crypto.randomUUID()}`, text: 'Do the thing' }], notes: '', attachment_ids: [], linked_map_id: null, ...extra })
const dec = (label, role_id, yes = null, no = null) => ({ id: aid(), kind: 'decision', label, role_id, system_id: null, tasks: [], notes: '', attachment_ids: [], linked_map_id: null, yes, no })
const save = (sec, revision, activities, changeDescription) => call(`section/save/${sec.id}`, { revision, activities, changeDescription })

step('1. Admin invites the owner; the owner accepts')
as('admin@demo.test')
const roles = call('role/list')
ok('role library is seeded', roles.length === 4 && call('system/list').length === 3)
as('owner@demo.test')
denied('owner cannot add a role', () => call('role/create', { name: 'Sneaky' }), 403)
as('admin@demo.test')
ok('admin can add a role', call('role/create', { name: 'Records Officer' }).name === 'Records Officer')
denied('duplicate role name refused', () => call('role/create', { name: 'records officer' }), 400)
// seeded owner exists; also prove the invitation flow with a fresh owner-role invite
const inv = call('invitation/create', { email: 'new.owner@demo.test', role: 'OWNER' })
as('owner@demo.test')
denied('owner cannot invite another OWNER', () => call('invitation/create', { email: 'x@demo.test', role: 'OWNER' }), 403)
call('auth/logout')
const acc = call('invitation/accept', { token: inv.token, name: 'New Owner', password: 'demo' })
ok('invitee accepted with OWNER role', acc.roles.includes('OWNER'))
denied('invitation cannot be reused', () => call('invitation/accept', { token: inv.token, name: 'x', password: 'demo' }), 400)

step('2. Owner invites contributors, creates the map, defines + assigns sections, kicks off')
as('admin@demo.test')
const hrFolder = call('folder/list').find((f) => f.name === 'HR')
const usersAll = call('user/list')
const hugo = usersAll.find((u) => u.email === 'hr.contrib@demo.test')
const ivy = usersAll.find((u) => u.email === 'it.contrib@demo.test')
const olivia = usersAll.find((u) => u.email === 'owner@demo.test')
call(`folder/edit/${hrFolder.id}`, { defaultExpertId: hugo.id, defaultMemberIds: [ivy.id] })
as('owner@demo.test')
const map = call('map/create', { title: 'New Employee Onboarding', description: 'From offer to day 30', objective: 'Get people productive fast', folderId: hrFolder.id, reviewIntervalDays: 365 })
ok('map code follows PM-{abbr}-{id}', /^PM-HR-\d+$/.test(map.code))
ok('folder default Expert and members are applied', map.expertId === hugo.id && call(`map/detail/${map.id}`).team.some((t) => t.id === ivy.id))
ok('objective is saved on the summary', map.summary.objective === 'Get people productive fast')
const v1 = map.openVersion.id
const s1 = call('section/create', { versionId: v1, title: 'HR admin', assigneeId: hugo.id })
const s2 = call('section/create', { versionId: v1, title: 'IT setup', assigneeId: ivy.id })
const s3 = call('section/create', { versionId: v1, title: 'Line manager tasks' })
denied('kickoff blocked while a section has no assignee', () => call(`version/kickoff/${v1}`), 400)
call(`section/assign/${s3.id}`, { assigneeId: olivia.id })
call(`version/kickoff/${v1}`)
ok('version is IN_PROGRESS', call(`version/detail/${v1}`).status === 'IN_PROGRESS')
as('hr.contrib@demo.test')
ok('contributor was notified of kickoff', call('notification/list').some((n) => /kicked off/.test(n.text)))

step('3. Contributors write different sections as outlines; locking is enforced by the server')
const t2 = act('Provision laptop', 2, { system_id: 2 })
const t3a = act('Ship laptop', 2)
const t3b = act('Hand over laptop at the desk', 2)
const t3 = dec('Remote worker?', 2, t3a.id, t3b.id)
const a1 = act('Create employee record', 1, { system_id: 1 })
const a1b = act('', 1) // blank label -> lint warning
let r = save(s1, 1, [a1, a1b])
ok('first save moves section to IN_PROGRESS', r.status === 'IN_PROGRESS' && r.revision === 2)
denied('stale revision -> 409', () => save(s1, 1, [a1]), 409)
denied('contributor cannot edit ANOTHER contributor\'s section (API, not UI)', () => save(s2, 1, [act('hack', 1)]), 403)
denied('contributor cannot approve own section', () => call(`section/approve/${s1.id}`), 403)
denied('contributor cannot kick off / add sections', () => call('section/create', { versionId: v1, title: 'sneaky' }), 403)
denied('activity ids must be unique across the map', () => save(s1, 2, [a1, a1b, { ...act('dup', 1), id: a1.id }]), 400)
denied('a decision cannot be the first step of the map', () => save(s1, 2, [dec('First?', 1), a1]), 400)
denied('decision pointing backwards (a loop) is refused', () => save(s1, 2, [a1, dec('Again?', 1, a1.id, null), a1b]), 400)
denied('decision pointing at an unknown step is refused', () => save(s1, 2, [a1, dec('Where?', 1, 'a_nope', null), a1b]), 400)
denied('unknown role is refused', () => save(s1, 2, [act('x', 999)]), 400)
const att = call('attachment/upload', { mapId: map.id, versionId: v1, sectionId: s1.id, activityId: a1.id, ogTitle: 'checklist.txt', attachTitle: 'Onboarding checklist', category: 'Checklist', dataUrl: 'data:text/plain;base64,SGVsbG8=', size: 5 })
ok('attachments default to INTERNAL', att.visibility === 'INTERNAL')
call('comment/create', { mapId: map.id, versionId: v1, sectionId: s1.id, activityId: a1.id, kind: 'COMMENT', body: 'Use the new HRIS form' })
denied('contributor cannot add REVISION comments', () => call('comment/create', { mapId: map.id, versionId: v1, kind: 'REVISION', body: 'x' }), 403)

as('it.contrib@demo.test')
r = save(s2, 1, [t2, t3, t3a, t3b]).revision
ok('IT saved its section', r === 2)
denied('IT cannot see/edit HR section', () => save(s1, 2, []), 403)
// cross-section jump: HR's last step jumps to IT's first step
as('hr.contrib@demo.test')
a1b.next = t2.id
ok('HR can jump to a step in the IT section', save(s1, 2, [a1, a1b]).revision === 3)
as('it.contrib@demo.test')
denied('IT cannot delete a step another section jumps to', () => save(s2, 2, [t3, t3a, t3b]), 409)

step('4. Submit with a change description; owner requests changes on IT setup, contributor fixes, owner approves all')
as('hr.contrib@demo.test')
denied('submit needs a change description', () => call(`section/submit/${s1.id}`, { changeDescription: '  ' }), 400)
call(`section/submit/${s1.id}`, { changeDescription: 'Wrote the HR admin steps' })
as('it.contrib@demo.test')
call(`section/submit/${s2.id}`, { changeDescription: 'Laptop provisioning' })
as('owner@demo.test')
const t4 = act('Schedule 1:1s', 3)
const endN = act('Day-30 review done', 3, { next: 'END' })
save(s3, 1, [t4, endN])
call(`section/submit/${s3.id}`, { changeDescription: 'Manager tasks' })
denied('request-changes needs a note', () => call(`section/request-changes/${s2.id}`, { note: '' }), 400)
call(`section/request-changes/${s2.id}`, { note: 'Add the MFA enrolment step' })
ok('map owner can edit ANOTHER contributor section', save(s2, 2, [t2, t3, t3a, t3b]).revision === 3)
as('it.contrib@demo.test')
denied('cannot resubmit while a revision comment is open / unchanged', () => call(`section/submit/${s2.id}`, { changeDescription: 'again' }), 400)
const mfa = act('Enrol MFA', 2)
save(s2, 3, [t2, t3, t3a, t3b, mfa])
denied('submit blocked by open REVISION comment', () => call(`section/submit/${s2.id}`, { changeDescription: 'Added MFA' }), 400)
const rev = call(`comment/list/${map.id}`).find((c) => c.kind === 'REVISION' && c.status === 'OPEN')
call(`comment/resolve/${rev.id}`)
call(`section/submit/${s2.id}`, { changeDescription: 'Added MFA enrolment' })
as('owner@demo.test')
for (const s of [s1, s2, s3]) call(`section/approve/${s.id}`)
ok('all sections approved', call(`version/detail/${v1}`).sections.every((s) => s.status === 'APPROVED'))
as('hr.contrib@demo.test')
denied('approved section is immutable', () => save(s1, 3, [a1]), 409)

step('5. Lint (warnings shown), then submit for publication with a change description')
as('owner@demo.test')
const lint = call(`version/lint/${v1}`)
ok('lint has warnings but no blockers', lint.blocking.length === 0 && lint.warnings.some((w) => w.code === 'NO_LABEL'))
as('hr.contrib@demo.test')
denied('contributor cannot submit for publication', () => call(`version/submit/${v1}`, { changeDescription: 'x' }), 403)
as('owner@demo.test')
denied('submit for publication needs a change description', () => call(`version/submit/${v1}`, { changeDescription: '' }), 400)
call(`version/submit/${v1}`, { changeDescription: 'First full draft of onboarding' })
const inReview = call(`version/detail/${v1}`)
ok('IN_REVIEW with immutable snapshot', inReview.status === 'IN_REVIEW' && inReview.snapshot.activities.length === 9)
ok('snapshot carries role and system names', inReview.snapshot.activities.find((a) => a.id === t2.id).roleName === 'IT Support' && inReview.snapshot.activities.find((a) => a.id === t2.id).systemName === 'Service Desk')
denied('chain enabled: submit never publishes directly (cannot self-approve)', () => call(`version/approve/${v1}`, {}), 403)
as('it.contrib@demo.test')
denied('IN_REVIEW: contributor cannot save', () => save(s2, 5, []), 409)

step('6. Approver rejects once; owner reopens a section; fixed; approved; PUBLISHED')
as('approver@demo.test')
denied('reject requires a note', () => call(`version/reject/${v1}`, { note: '' }), 400)
call(`version/reject/${v1}`, { note: 'Line manager section needs a probation step' })
as('owner@demo.test')
ok('rejected -> CHANGES_REQUESTED, back with the owner', call(`version/detail/${v1}`).status === 'CHANGES_REQUESTED')
denied('reopen needs at least one section', () => call(`version/reopen/${v1}`, { sectionIds: [] }), 400)
call(`version/reopen/${v1}`, { sectionIds: [s3.id] })
const det = call(`version/detail/${v1}`)
ok('only the reopened section is ASSIGNED, others stay APPROVED', det.sections.find((s) => s.id === s3.id).status === 'ASSIGNED' && det.sections.filter((s) => s.status === 'APPROVED').length === 2)
const prob = act('Probation check-in', 3)
save(s3, 2, [t4, prob, endN])
call(`section/submit/${s3.id}`, { changeDescription: 'Added probation check-in' })
call(`section/approve/${s3.id}`)
call(`version/submit/${v1}`, { changeDescription: 'Added probation step after approver feedback' })
ok('submitter is excluded from pending approvers', !call(`version/detail/${v1}`).approval.pendingApprovers.some((p) => p.name === 'Olivia Owner'))
as('viewer@demo.test')
denied('viewer cannot approve', () => call(`version/approve/${v1}`, {}), 403)
as('approver@demo.test')
call(`version/approve/${v1}`, { note: 'Looks good' })
as('owner@demo.test')
ok('version PUBLISHED', call(`version/detail/${v1}`).status === 'PUBLISHED')

step('7. Viewer finds the map by search, opens it read-only, sends feedback on a step')
as('viewer@demo.test')
const hits = call('published/search', { q: 'laptop' })
ok('search finds the map via an activity label', hits.some((h) => h.id === map.id))
ok('search finds the map via a role name', call('published/search', { q: 'it support' }).some((h) => h.id === map.id))
ok('search for gibberish finds nothing', call('published/search', { q: 'zzzxqy' }).length === 0)
const pm = call(`published/map/detail/${map.id}`)
ok('published view serves the snapshot', pm.snapshot.sections.length === 3 && pm.snapshot.activities.length === 10)
ok('internal attachment hidden from viewers', pm.attachments.length === 0)
denied('viewer cannot open the unpublished authoring detail', () => call(`map/detail/${map.id}`), 403)
denied('viewer cannot comment in authoring', () => call('comment/create', { mapId: map.id, versionId: v1, kind: 'COMMENT', body: 'x' }), 403)
const fb = call('published/feedback/create', { mapId: map.id, activityId: t3.id, body: 'Which laptop model?', responseRequired: true })
ok('feedback is anchored to an activity and can require a response', fb.activityId === t3.id && fb.responseRequired === true)
as('owner@demo.test')
ok('owner notified of feedback', call('notification/list').some((n) => /feedback/i.test(n.text)))
call('comment/create', { mapId: map.id, versionId: v1, parentId: fb.id, kind: 'COMMENT', body: 'Standard Dell, see the checklist' })
call(`comment/resolve/${fb.id}`)
ok('owner can resolve a feedback thread', call(`comment/list/${map.id}`).find((c) => c.id === fb.id).status === 'RESOLVED')
call(`comment/reopen/${fb.id}`)
ok('owner can reopen a resolved thread', call(`comment/list/${map.id}`).find((c) => c.id === fb.id).status === 'OPEN')
as('viewer@demo.test')
ok('feedback author is told about the reply', call('notification/list').some((n) => /replied to your feedback/.test(n.text)))
as('owner@demo.test')
call(`attachment/toggle-portal/${att.id}`)
as('viewer@demo.test')
ok('attachment visible after owner flips it', call(`published/map/detail/${map.id}`).attachments.length === 1)
call('auth/logout')
denied('anonymous cannot read published maps', () => call('published/map/list'), 401)

step('8. Version 2 with a change note; v1 stays live until v2 is approved')
as('owner@demo.test')
denied('change note required', () => call(`version/create-draft/${map.id}`, { changeNote: '' }), 400)
const v2 = call(`version/create-draft/${map.id}`, { changeNote: 'Add contractor path' })
denied('only one open version at a time', () => call(`version/create-draft/${map.id}`, { changeNote: 'again' }), 400)
const v2d = call(`version/detail/${v2.id}`)
ok('v2 sections cloned as APPROVED with assignees retained', v2d.sections.length === 3 && v2d.sections.every((s) => s.status === 'APPROVED' && s.assigneeId))
ok('v2 sections keep their activities', v2d.sections.reduce((n, s) => n + s.activityCount, 0) === 10)
denied('kickoff needs a reopened section', () => call(`version/kickoff/${v2.id}`), 400)
call(`version/reopen/${v2.id}`, { sectionIds: [v2d.sections[0].id] })
call(`version/kickoff/${v2.id}`)
as('viewer@demo.test')
ok('portal still shows version 1', call(`published/map/detail/${map.id}`).versionNo === 1)

step('9. Review cycle: Mark as reviewed creates no new version')
as('it.contrib@demo.test')
denied('IT contributor cannot mark the map as reviewed', () => call(`map/mark-reviewed/${map.id}`, { note: 'ok' }), 403)
as('owner@demo.test')
denied('review needs a note', () => call(`map/mark-reviewed/${map.id}`, { note: '' }), 400)
const before = call(`map/detail/${map.id}`).versions.length
const rv = call(`map/mark-reviewed/${map.id}`, { note: 'Re-read, still accurate' })
ok('marked reviewed: date moves, no new version', !!rv.lastReviewedAt && call(`map/detail/${map.id}`).versions.length === before)
as('hr.contrib@demo.test')
ok('the Expert may mark the map as reviewed', call(`map/mark-reviewed/${map.id}`, { note: 'Expert check' }).lastReviewedAt)
ok('change log shows the review', (as('owner@demo.test'), call(`changelog/list/${map.id}`).some((c) => /reviewed/.test(c.text))))

step('Approval chain guard: only the submitter eligible -> submit refused')
as('admin@demo.test')
const chain = call('approval-chain/preset-list/PROCESS_MAP')
denied('non-APPROVER cannot be a stage approver', () => call('approval-chain/save/PROCESS_MAP', { enabled: true, stages: [{ name: 'S', rule: 'ANY_ONE', approvers: [hugo.id] }] }), 400)
ok('chain config readable', chain.enabled && chain.stages.length === 1)
as('owner@demo.test')
denied('owner cannot change approval chain', () => call('approval-chain/save/PROCESS_MAP', { enabled: false, stages: [] }), 403)

step('To-do list, summary, tags and change log')
as('owner@demo.test')
const td = call('todo/create', { mapId: map.id, title: 'Collect signed forms', assigneeId: hugo.id, dueDate: '2026-12-01' })
as('hr.contrib@demo.test')
ok('assignee sees the to-do in their list', call('todo/my').some((t) => t.id === td.id && !t.done))
denied('contributor cannot assign a to-do', () => call('todo/create', { mapId: map.id, title: 'x', assigneeId: hugo.id }), 403)
ok('assignee can tick it off', call(`todo/toggle/${td.id}`).done === true)
as('it.contrib@demo.test')
denied('someone else cannot tick it off', () => call(`todo/toggle/${td.id}`), 403)
as('owner@demo.test')
ok('owner notified of completion', call('notification/list').some((n) => /completed: Collect signed forms/.test(n.text)))
call(`map/edit/${map.id}`, { tags: ['hr', ' hr ', 'onboarding'], summary: { objective: 'Get people productive' } })
const md = call(`map/detail/${map.id}`)
ok('tags are de-duplicated and summary saved', md.tags.length === 2 && md.summary.objective === 'Get people productive')
ok('change log is readable and carries change descriptions', call(`changelog/list/${map.id}`).some((c) => /published/.test(c.text)) && call(`changelog/list/${map.id}`).some((c) => /probation/i.test(c.note || '')))
as('hr.contrib@demo.test')
denied('contributor cannot edit the summary', () => call(`map/edit/${map.id}`, { summary: { objective: 'x' } }), 403)

console.log(`\n${passed} checks passed, ${failed} failed.`)
process.exit(failed ? 1 : 0)
